PALKHI_DEVIATION = "palkhi_deviation"
PALKHI_SIGNAL_LOST = "palkhi_signal_lost"
PALKHI_OFF_ROUTE = "palkhi_off_route"

#: A pace estimate built on fewer than this many pings inside the window is a
#: guess about a walking group made from two dots on a map.  It still produces
#: an alert, but a different one — R-M8-04, which asks somebody to phone the
#: Dindi leader rather than telling a town to move its kitchen.
MIN_PACE_SAMPLES = 4


@dataclass(frozen=True, slots=True)
class DindiSignal:
    """One Dindi's progress against its own schedule, as the rules see it.

    `deviation_minutes` is **signed, and the sign is the important part**:
    positive means arriving later than planned, negative means earlier.  It is
    tempting to collapse this to one magnitude against one threshold, and it is
    wrong.  Late means a town waits with the food going cold.  Early means five
    hundred people walk into a town whose water tankers have not arrived — which
    is the failure Section 4/M8 exists to prevent, and the reason the rules
    below are harder on a fast Dindi than on a slow one.
    """

    dindi_name: str
    dindi_name_mr: str
    next_town: str
    next_town_mr: str
    deviation_minutes: float
    planned_arrival: datetime
    eta: datetime
    expected_count: int
    pace_kmph: float
    km_remaining: float
    #: ready | partial | not_ready | unknown, from the halt town's own board.
    next_town_readiness: str = "unknown"
    #: How many pings the pace was averaged over.
    pace_samples: int = 0

    @property
    def is_late(self) -> bool:
        return self.deviation_minutes > 0

    @property
    def is_confident(self) -> bool:
        return self.pace_samples >= MIN_PACE_SAMPLES and self.pace_kmph > 0.5

    @property
    def town_is_ready(self) -> bool:
        return self.next_town_readiness == "ready"


@dataclass(frozen=True, slots=True)
class DindiRule:
    """A deviation rule whose action names the town, the gap and the group size.

    Same contract as `ForecastRule`: every number in the sentence comes from the
    signal and from nothing else.  A halt-town coordinator being told to move an
    overnight kitchen needs to see *why* — "Saswad, 62 min early, 400 walkers" —
    not a fluent sentence about a schedule a model inferred.
    """

    id: str
    severity: AlertSeverity
    matches: Callable[[DindiSignal, Thresholds], bool]
    template: str
    template_mr: str

    def as_rule(self) -> Rule:
        """Adapter so `rule_by_id` resolves a palkhi rule from an alert row."""
        return Rule(
            id=self.id,
            alert_type=PALKHI_DEVIATION,
            severity=self.severity,
            metric="deviation_minutes",
            threshold=Thresholds().dindi_deviation_minutes,
            matches=lambda s, t: False,  # dispatched by `evaluate_dindi`, never by CrowdSignal
            action=self.template,
            action_mr=self.template_mr,
        )


def _breaches(signal: DindiSignal, thresholds: Thresholds) -> bool:
    return abs(signal.deviation_minutes) > thresholds.dindi_deviation_minutes


