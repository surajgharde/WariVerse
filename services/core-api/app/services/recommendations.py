@dataclass(frozen=True, slots=True)
class ForecastRecommendation:
    rule: ForecastRule
    signal: ForecastSignal
    hold_minutes: int
    action: str
    action_mr: str


def evaluate_forecast(
    signal: ForecastSignal, thresholds: Thresholds | None = None
) -> ForecastRecommendation | None:
    """First matching forecast rule with its numbers filled in, or None.

    The trigger and every number in the returned sentence come from this
    function.  Section 4/M6: "An LLM may phrase the recommendation, but the
    trigger and the numbers come from the rules table. Never let a language
    model invent a safety instruction."
    """
    bands = thresholds or Thresholds()
    for rule in FORECAST_RULES:
        if not rule.matches(signal, bands):
            continue
        hold = hold_minutes(signal, bands)
        fields = {
            "zone_name": signal.zone_name,
            "zone_name_mr": signal.zone_name_mr,
            "gate_name": signal.gate_name,
            "gate_name_mr": signal.gate_name_mr,
            "density": signal.predicted_density,
            "low": signal.interval_low,
            "high": signal.interval_high,
            "horizon": signal.horizon_minutes,
            "target": signal.target_at,
            "hold": hold,
        }
        return ForecastRecommendation(
            rule=rule,
            signal=signal,
            hold_minutes=hold,
            action=rule.template.format(**fields),
            action_mr=rule.template_mr.format(**fields),
        )
    return None


