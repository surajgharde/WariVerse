@dataclass(frozen=True, slots=True)
class DindiRecommendation:
    rule: DindiRule
    signal: DindiSignal
    action: str
    action_mr: str

    @property
    def gap_minutes(self) -> int:
        return int(round(abs(self.signal.deviation_minutes)))


def evaluate_dindi(signal: DindiSignal, thresholds: Thresholds | None = None) -> DindiRecommendation | None:
    """First matching deviation rule with its numbers filled in, or None.

    None is the answer for a Dindi inside its threshold, which is most of them
    most of the time — eighteen days of walking produce a great many readings
    that mean "still on schedule", and not one of them should reach an operator.
    """
    bands = thresholds or Thresholds()
    for rule in DINDI_RULES:
        if not rule.matches(signal, bands):
            continue
        fields = {
            "dindi_name": signal.dindi_name,
            "dindi_name_mr": signal.dindi_name_mr,
            "next_town": signal.next_town,
            "next_town_mr": signal.next_town_mr,
            "gap": int(round(abs(signal.deviation_minutes))),
            "planned": signal.planned_arrival,
            "eta": signal.eta,
            "count": signal.expected_count,
            "pace": signal.pace_kmph,
            "km": signal.km_remaining,
            "samples": signal.pace_samples,
            "readiness": signal.next_town_readiness.replace("_", " "),
            "readiness_mr": _READINESS_MR.get(signal.next_town_readiness, signal.next_town_readiness),
        }
        return DindiRecommendation(
            rule=rule,
            signal=signal,
            action=rule.template.format(**fields),
            action_mr=rule.template_mr.format(**fields),
        )
    return None
