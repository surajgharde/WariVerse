@dataclass(frozen=True, slots=True)
class Recommendation:
    rule: Rule
    trigger_value: float

    @property
    def action(self) -> str:
        return self.rule.action

    @property
    def action_mr(self) -> str:
        return self.rule.action_mr


def evaluate(signal: CrowdSignal, thresholds: Thresholds | None = None) -> Recommendation | None:
    """First matching rule, or None when the zone is behaving.

    One reading produces at most one alert.  Firing three overlapping alerts for
    one stalled corridor is how an alert feed becomes wallpaper, and wallpaper
    is how a real alert gets missed.
    """
    bands = thresholds or Thresholds()
    for rule in RULES:
        if rule.matches(signal, bands):
            return Recommendation(rule=rule, trigger_value=rule.value_of(signal))
    return None


def rule_by_id(rule_id: str) -> Rule | None:
    for rule in (*RULES, CAMERA_OFFLINE_RULE):
        if rule.id == rule_id:
            return rule
    return None
