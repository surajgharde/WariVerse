"""The recommendation rule table (Section 4/M2 step 5, Section 0 rule 3).

Every alert this system raises carries a suggested action, and every suggested
action comes from a numbered rule in this table.  Nothing here is generated by a
language model, and nothing here is generated by the detector.  An operator who
is about to close a gate on ten thousand people gets to see *which rule* said
so, which is what `Alert.rule_id` is for.

Order matters: the list is evaluated top to bottom and the first match wins, so
the most specific and most dangerous condition is first.  A dense crowd that has
stopped moving is not "a high density alert plus a stagnation alert" — it is one
situation with one correct response.

The Marathi is the operational text.  The control room in Pandharpur runs in
Marathi; the English is the translation, not the other way around.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass

from app.models.crowd import AlertSeverity

# Alert type names.  These are stored on the row and switched on by the UI —
# keep them stable.
DENSITY_CRITICAL = "density_critical"
DENSITY_HIGH = "density_high"
STAGNATION = "stagnation"
COUNTERFLOW = "counterflow"
CAMERA_OFFLINE = "camera_offline"

#: Section 4/M2: stagnation only alerts *with* density above this.  A still,
#: empty plaza at 3 a.m. has a stagnation index of 1.0 and means nothing.
STAGNATION_DENSITY_FLOOR = 3.0


@dataclass(frozen=True, slots=True)
class CrowdSignal:
    """The measured state of one zone at one moment, as the rules see it."""

    density: float
    stagnation_index: float
    counterflow_ratio: float
    person_count: int
    confidence: float = 1.0
    zone_name: str = "this zone"
    zone_name_mr: str = "हा विभाग"


@dataclass(frozen=True, slots=True)
class Rule:
    id: str
    alert_type: str
    severity: AlertSeverity
    metric: str
    threshold: float
    matches: Callable[[CrowdSignal, Thresholds], bool]
    action: str
    action_mr: str

    def value_of(self, signal: CrowdSignal) -> float:
        return float(getattr(signal, self.metric))


@dataclass(frozen=True, slots=True)
class Thresholds:
    """Operator-tunable bands, read from `system_config` at evaluation time."""

    density_high: float = 3.5
    density_critical: float = 5.0
    stagnation: float = 0.70
    counterflow: float = 0.35


