FORECAST_HIGH = "forecast_high"

#: Below this the interval is too wide to act on.  A prediction of 4.2 p/m²
#: with a band from 1.1 to 7.0 is not a forecast of a crush, it is the model
#: saying it does not know — and holding a gate on that is how operators learn
#: to ignore the forecast strip entirely.
MAX_ACTIONABLE_INTERVAL_WIDTH = 2.5


@dataclass(frozen=True, slots=True)
class ForecastSignal:
    """One prediction, as the rules see it.

    Carries the interval and not just the point estimate, because the rules
    below refuse to fire on a prediction the model is not sure about, and they
    cannot make that judgement from a single number.
    """

    predicted_density: float
    interval_low: float
    interval_high: float
    horizon_minutes: int
    target_at: datetime
    zone_name: str = "this zone"
    zone_name_mr: str = "हा विभाग"
    gate_name: str = "the upstream gate"
    gate_name_mr: str = "वरचे द्वार"

    @property
    def interval_width(self) -> float:
        return self.interval_high - self.interval_low

    @property
    def is_actionable(self) -> bool:
        return self.interval_width <= MAX_ACTIONABLE_INTERVAL_WIDTH


@dataclass(frozen=True, slots=True)
class ForecastRule:
    """A rule whose action carries the forecast's own numbers.

    Unlike the M2 rules, whose actions are fixed sentences, Section 4/M6 asks
    for a *concrete* suggestion — "hold Gate 2 intake for 12 min" — which means
    the numbers have to come from the prediction.  They come from the prediction
    and from the arithmetic below, and from nothing else.  A language model may
    rephrase what this produces; it may not produce it.
    """

    id: str
    severity: AlertSeverity
    threshold: float
    matches: Callable[[ForecastSignal, Thresholds], bool]
    template: str
    template_mr: str

    def as_rule(self) -> Rule:
        """Adapter so `rule_by_id` can resolve forecast rules from an alert row."""
        return Rule(
            id=self.id,
            alert_type=FORECAST_HIGH,
            severity=self.severity,
            metric="density",
            threshold=self.threshold,
            matches=lambda s, t: False,  # dispatched by `evaluate_forecast`, never by CrowdSignal
            action=self.template,
            action_mr=self.template_mr,
        )


def hold_minutes(signal: ForecastSignal, thresholds: Thresholds) -> int:
    """How long to hold intake, in whole minutes.

    Proportional to how far the prediction sits above the band it is crossing,
    and capped at the horizon: a hold longer than the forecast that justified it
    is a hold with no evidence behind its tail.  Rounded up to five-minute steps
    because a gate marshal cannot act on "hold for 7 minutes", and rounding down
    would under-serve the case the rule exists for.
    """
    excess = max(0.0, signal.predicted_density - thresholds.density_high)
    raw = 5.0 + excess * 8.0
    stepped = 5 * int((raw + 4.999) // 5)
    return int(min(stepped, signal.horizon_minutes))


